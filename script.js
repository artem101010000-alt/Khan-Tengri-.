const tabs = document.getElementById('menuTabs');
const panel = document.getElementById('menuPanel');
const fmt = p => p ? p + '\u00a0₸' : '';

function renderCat(i) {
  const cat = MENU[i];
  panel.innerHTML = '';
  const list = document.createElement('ul');
  list.className = 'mlist';
  cat.items.forEach(([name, price, desc]) => {
    const li = document.createElement('li');
    const top = document.createElement('div');
    top.className = 'mrow';
    const n = document.createElement('span'); n.className = 'mname'; n.textContent = name;
    const d = document.createElement('span'); d.className = 'mdots';
    const p = document.createElement('span'); p.className = 'mprice'; p.textContent = fmt(price);
    top.append(n, d, p);
    if (!price) d.style.visibility = 'hidden';
    li.appendChild(top);
    if (desc) { const e = document.createElement('p'); e.className = 'mdesc'; e.textContent = desc; li.appendChild(e); }
    list.appendChild(li);
  });
  panel.appendChild(list);
  panel.classList.remove('swap'); void panel.offsetWidth; panel.classList.add('swap');
  tabs.querySelectorAll('button').forEach((b, k) => {
    b.classList.toggle('active', k === i);
    b.setAttribute('aria-selected', k === i);
  });
}
MENU.forEach((cat, i) => {
  const b = document.createElement('button');
  b.type = 'button'; b.role = 'tab'; b.textContent = cat.title;
  b.addEventListener('click', () => {
    renderCat(i);
    b.scrollIntoView({ inline: 'center', block: 'nearest', behavior: 'smooth' });
  });
  tabs.appendChild(b);
});
renderCat(0);

